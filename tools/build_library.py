#!/usr/bin/env python3
"""Builds the app's colouring-book library from the source pictures.

  assets/draw_lib/<category>/NN_name.png   (source: generated pictures)
        |
        v   this script
  assets/library/<category>/NN_name.png    (what the app bundles)
  lib/core/library/catalog.dart            (generated list of drawings)
  pubspec.yaml                             (asset folders, between markers)

Each picture is turned into a clean, light grey-scale PNG: the long side is
set to LONG_SIDE, paper noise is removed with a levels curve and the grey
levels are reduced. The app then runs it through the same scan as a photo.

Needs Pillow:  python3 -m venv .venv && .venv/bin/pip install pillow
Run from the repository root:  .venv/bin/python tools/build_library.py
"""
import json
import re
import shutil
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "draw_lib"
OUT = ROOT / "assets" / "library"
NAMES = ROOT / "tools" / "library_names.json"
CATALOG = ROOT / "lib" / "core" / "library" / "catalog.dart"
PUBSPEC = ROOT / "pubspec.yaml"

# Order of the categories in the app. Each folder name is also the name of the
# `DrawingCategory` value in lib/core/library/drawing.dart.
CATEGORIES = [
    "animals", "dinosaurs", "ocean", "forest", "cars", "train",
    "city", "space", "princess", "toys", "plush", "food",
]

LONG_SIDE = 1280
BLACK_BELOW, WHITE_ABOVE = 90, 195  # levels curve: removes paper noise
GREY_LEVELS = 16
FILE_RE = re.compile(r"^\d{2}_[a-z0-9_]+\.png$")


def convert(src: Path, dst: Path) -> None:
    img = Image.open(src).convert("L")
    scale = LONG_SIDE / max(img.size)
    size = (round(img.width * scale), round(img.height * scale))
    img = img.resize(size, Image.LANCZOS)
    span = WHITE_ABOVE - BLACK_BELOW
    step = 255 / (GREY_LEVELS - 1)
    lut = []
    for v in range(256):
        t = min(1.0, max(0.0, (v - BLACK_BELOW) / span))
        lut.append(round(round(t * (GREY_LEVELS - 1)) * step))
    img = img.point(lut)
    dst.parent.mkdir(parents=True, exist_ok=True)
    img.save(dst, "PNG", optimize=True)


def dart_string(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def write_catalog(entries: list[tuple[str, str, str, str]]) -> None:
    lines = [
        "// GENERATED by tools/build_library.py - do not edit by hand.",
        "import 'drawing.dart';",
        "",
        "/// Every ready-made colouring page that ships with the app.",
        "const List<Drawing> kDrawings = [",
    ]
    for drawing_id, name, category, asset in entries:
        lines.append(
            f"  Drawing({dart_string(drawing_id)}, {dart_string(name)}, "
            f"DrawingCategory.{category}, {dart_string(asset)}),"
        )
    lines += [
        "];",
        "",
        "List<Drawing> drawingsIn(DrawingCategory category) =>",
        "    [for (final d in kDrawings) if (d.category == category) d];",
        "",
    ]
    CATALOG.write_text("\n".join(lines))


def write_pubspec(categories: list[str]) -> None:
    begin, end = "    # library-assets:begin", "    # library-assets:end"
    text = PUBSPEC.read_text()
    block = begin + "\n" + "".join(
        f"    - assets/library/{c}/\n" for c in categories
    ) + end
    if begin in text:
        text = re.sub(re.escape(begin) + r".*?" + re.escape(end), block, text, flags=re.S)
    else:
        anchor = "  assets:\n"
        if anchor not in text:
            sys.exit("pubspec.yaml has no 'assets:' section")
        text = text.replace(anchor, anchor + block + "\n", 1)
    PUBSPEC.write_text(text)


def main() -> None:
    names = json.loads(NAMES.read_text())
    entries, missing_names, kept = [], [], set()
    total_in = total_out = 0

    for category in CATEGORIES:
        folder = SRC / category
        files = sorted(p for p in folder.glob("*.png") if FILE_RE.match(p.name)) if folder.is_dir() else []
        if not files:
            print(f"warning: no pictures in {folder}", file=sys.stderr)
        for src in files:
            stem = src.stem
            key = f"{category}/{stem}"
            dst = OUT / category / src.name
            convert(src, dst)
            kept.add(dst)
            total_in += src.stat().st_size
            total_out += dst.stat().st_size
            name = names.get(key)
            if name is None:
                missing_names.append(key)
                name = stem.split("_", 1)[1].replace("_", " ").title()
            entries.append((key, name, category, f"assets/library/{category}/{src.name}"))

    # Drop converted files whose source no longer exists.
    for old in OUT.glob("*/*.png"):
        if old not in kept:
            old.unlink()
            print("removed stale", old.relative_to(ROOT))
    for folder in OUT.glob("*/"):
        if folder.is_dir() and not any(folder.iterdir()):
            shutil.rmtree(folder)

    present = [c for c in CATEGORIES if any(e[2] == c for e in entries)]
    write_catalog(entries)
    write_pubspec(present)

    print(f"{len(entries)} drawings in {len(present)} categories")
    print(f"size: {total_in / 1e6:.1f} MB -> {total_out / 1e6:.1f} MB")
    if missing_names:
        print("no display name in tools/library_names.json for:", *missing_names, sep="\n  ")


if __name__ == "__main__":
    main()
